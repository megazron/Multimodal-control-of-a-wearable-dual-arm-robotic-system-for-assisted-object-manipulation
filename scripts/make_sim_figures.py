#!/usr/bin/env python3
"""TURN A SIMULATION CAMPAIGN INTO THE THESIS'S TABLES AND FIGURES.

    python3 scripts/make_sim_figures.py                       # newest campaign
    python3 scripts/make_sim_figures.py --campaign recordings/simulations/<x>
    python3 scripts/make_sim_figures.py --self-test

WHY THIS EXISTS.  Numbers reached the thesis by being copied out of a
terminal, which means a re-run changes nothing in the document and a document
figure cannot be traced to the run that produced it.  Everything this writes
carries the campaign stamp it was generated from, so a figure in the PDF names
the directory a reader can check it against.

IT REFUSES RATHER THAN INVENTS.  A stage that did not run produces no table.
There is no default, no last-known-good and no placeholder: a missing result
must be visibly missing, because a table of plausible numbers with no run
behind it is the worst artefact this project could produce.
"""
