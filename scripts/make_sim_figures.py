class Missing(Exception):
    """A result this figure needs was not produced by the campaign."""


def newest_campaign():
    ds = sorted(glob.glob(os.path.join(WS, "recordings", "simulations", "*")))
    ds = [d for d in ds if os.path.exists(os.path.join(d, "campaign.json"))]
    if not ds:
        raise Missing("no campaign with a campaign.json under "
                      "recordings/simulations")
    return ds[-1]


def load(camp):
    with open(os.path.join(camp, "campaign.json")) as fh:
        run = json.load(fh)
    by = {s["key"]: s for s in run["stages"]}
    return run, by


def load_many(camps):
    """Merge several campaign directories into one view.

    The standalone stages and the ones needing a live `move_group` are run
    separately -- one MoveIt stack for all of the latter, because HARD
    CONSTRAINT 3 forbids two and two verifiers against one `move_group` have
    already produced a measurement where one run's furniture was in the
    other's scene. Merging here is what lets the thesis report them as one
    campaign, which is what they are.

    A later directory WINS on a key it also has, and it wins whatever its
    status: a re-run that failed must not be masked by an older success.
    Each stage remembers the directory it actually came from, so a figure can
    always name the run behind it.
    """
    merged, stamps, homes = {}, [], {}
    for c in camps:
        run, by = load(c)
        stamps.append(run.get("stamp", os.path.basename(c)))
        for k, v in by.items():
            merged[k] = v
            homes[k] = c
    return merged, homes, "+".join(stamps)


def need(by, key):
    st = by.get(key)
    if st is None:
        raise Missing("stage %s is not in this campaign" % key)
    if st.get("status") != "ok":
        raise Missing("stage %s did not succeed (%s)"
                      % (key, st.get("status")))
    return st


def log_of(camp, key):
    if isinstance(camp, dict):                # a homes map from load_many
        camp = camp.get(key, "")
    p = os.path.join(camp, "logs", key + ".log")
    if not os.path.exists(p):
        raise Missing("no log for %s" % key)
    return open(p).read()


def head(stamp, what):
    return ("%% GENERATED by scripts/make_sim_figures.py from simulation\n"
            "%% campaign %s. Do not edit: re-run the campaign instead.\n"
            "%% %s\n" % (stamp, what))


