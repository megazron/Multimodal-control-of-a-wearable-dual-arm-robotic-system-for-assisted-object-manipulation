def orientation_convergence(camp, by, stamp):
    """The same sweep at every sampling density it was run at.

    Read from the LOGS of every campaign on disk rather than from the
    baseline file, because each run overwrites that file and the point of
    this table is the DIFFERENCE between runs. A single column would be a
    number; the set of columns is the finding.
    """
    runs = []
    for c in sorted(CAMPAIGNS):
        lg = os.path.join(c, "logs", "teleop_orientation_cost.log")
        cj = os.path.join(c, "campaign.json")
        if not (os.path.exists(lg) and os.path.exists(cj)):
            continue
        txt = open(lg).read()
        means = dict((k, (float(v), int(w))) for k, v, w in _MEAN_RE.findall(txt))
        if len(means) != 5:
            continue
        argv = " ".join(json.load(open(cj)).get("argv", []))
        st = [x for x in json.load(open(cj))["stages"]
              if x["key"] == "teleop_orientation_cost"]
        seeds = None
        for x in st:
            a = x.get("argv", [])
            if "--seeds" in a:
                seeds = int(a[a.index("--seeds") + 1])
        if seeds is None:
            continue
        bad = _CTRL3_RE.search(txt)
        roll = _ROLL_RE.search(txt)
        # WHICH VERSION OF THE CONTROL RAN. Two runs share a seed count and
        # differ only in whether capped walks are excluded from the
        # monotonicity test, so the seed count alone does not identify a
        # column. The corrected control announces its exclusions; the older
        # one had nothing to announce.
        fixed = "EXCLUDED because the tighter policy hit the search cap" in txt
        runs.append(dict(seeds=seeds, means=means, fixed=fixed,
                         skipped=len(re.findall(r"\(CAPPED\) vs", txt)),
                         bad=int(bad.group(1)) if bad else 0,
                         roll=int(roll.group(1)) if roll else None))
    if len(runs) < 2:
        raise Missing("fewer than two orientation sweeps on disk; the point "
                      "of this table is the difference between them")
    runs.sort(key=lambda r: (r["seeds"], r["fixed"]))
    label = [("pinned", "pinned to the anchor (delivered)"),
             ("spin", "roll free"),
             ("cone15", "\\SI{15}{\\degree} cone"),
             ("cone45", "\\SI{45}{\\degree} cone"),
             ("free", "position only")]
    cols = " & ".join(
        ("\\begin{tabular}{@{}c@{}}%d seeds\\\\\\scriptsize %s"
         "\\end{tabular}") % (r["seeds"],
                              "capped walks excluded" if r["fixed"]
                              else "all walks compared")
        for r in runs)
    body = []
    for key, nice in label:
        body.append("    %s & %s \\\\"
                    % (nice, " & ".join("\\num{%.3f}" % r["means"][key][0]
                                        for r in runs)))
    body.append("    \\midrule")
    body.append("    what the roll appears to buy & %s \\\\"
                % " & ".join(("$%+d$\\,mm" % r["roll"]) if r["roll"] is not None
                             else "---" for r in runs))
    body.append("    walks stopped by the wearer, of 28 & %s \\\\"
                % " & ".join(str(r["means"]["pinned"][1]) for r in runs))
    body.append("    a looser policy reached \\emph{less} far & %s \\\\"
                % " & ".join("\\textbf{%d}" % r["bad"] for r in runs))
    body.append("    excluded as capped lower bounds & %s \\\\"
                % " & ".join(("%d" % r["skipped"]) if r["fixed"] else "---"
                             for r in runs))
    return (head(stamp, "the orientation sweep at every sampling density")
            + "\\footnotesize\n\\begin{tabular}{@{}l%s@{}}\n" % ("c" * len(runs))
            + "  \\toprule\n"
              "  & \\multicolumn{%d}{c}{mean reach over 28 walks, \\si{\\metre}} \\\\\n"
              % len(runs)
            + "  \\cmidrule(l){2-%d}\n" % (len(runs) + 1)
            + "  Orientation policy & %s \\\\\n" % cols
            + "  \\midrule\n"
            + "\n".join(body)
            + "\n  \\bottomrule\n\\end{tabular}\n")


def _tex(s):
    for a, b in (("\\", "\\textbackslash "), ("_", "\\_"), ("%", "\\%"),
                 ("&", "\\&"), ("#", "\\#"), ("$", "\\$")):
        s = s.replace(a, b)
    return s


GROUP_LABEL = {
    "computer vision": "computer vision",
    "teleoperation": "teleoperation",
    "robot tasks": "robot tasks",
    "autonomy": "autonomy",
    "study": "study design",
    "transfer": "transfer to hardware",
}
TIER_LABEL = {"standalone": "standalone", "stack": "simulated platform",
              "recorded": "recorded data"}
STATUS_LABEL = {"ok": "\\checkmark", "failed": "\\textbf{failed}",
                "skipped": "\\textit{not run}",
                "missing": "\\textbf{missing}"}


def _secs(v):
    """Durations that read as a duration. A sub-second stage shown as
    `0 s` reads like a stage that did not run, which is the one thing this
    column must never be confusable with."""
    if v is None:
        return "---"
    if v < 1:
        return "$<\\SI{1}{\\second}$"
    if v < 100:
        return "\\SI{%.0f}{\\second}" % v
    return "\\SI{%.1f}{\\minute}" % (v / 60.0)


def campaign_inventory(camp, by, stamp):
    """Every stage, its tier and its outcome. The whole campaign on one page.

    Ordered by group and then by key so a re-run produces the same table, and
    NOT by duration, which would reorder the rows on every machine.
    """
    if not by:
        raise Missing("the campaign has no stages")
    order = ["computer vision", "teleoperation", "robot tasks", "autonomy",
             "study", "transfer"]
    rows = sorted(by.values(),
                  key=lambda s: (order.index(s["group"])
                                 if s.get("group") in order else 99,
                                 s["key"]))
    body, seen = [], None
    for r in rows:
        g = GROUP_LABEL.get(r.get("group"), r.get("group", "?"))
        if g != seen:
            if seen is not None:
                body.append("    \\addlinespace[2pt]")
            body.append("    \\multicolumn{4}{@{}l}{\\itshape %s} \\\\" % g)
            seen = g
        secs = r.get("seconds")
        body.append("    \\quad \\repo{%s} & %s & %s & %s \\\\"
                    % (r["key"].replace("_", "\\_"),
                       TIER_LABEL.get(r.get("tier"), r.get("tier", "?")),
                       STATUS_LABEL.get(r.get("status"), r.get("status", "?")),
                       _secs(secs)))
    return (head(stamp, "the campaign, stage by stage")
            + "\\begin{tabular}{@{}llcr@{}}\n"
              "  \\toprule\n"
              "  Stage & Needs & Ran & Time \\\\\n"
              "  \\midrule\n"
            + "\n".join(body)
            + "\n  \\bottomrule\n\\end{tabular}\n")


