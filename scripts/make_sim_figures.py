def self_test():
    """The generators must REFUSE on a campaign that produced nothing."""
    import tempfile
    ok = fail = 0

    def check(name, cond):
        nonlocal ok, fail
        if cond:
            ok += 1
            print("  ok    %s" % name)
        else:
            fail += 1
            print("  FAIL  %s" % name)

    with tempfile.TemporaryDirectory() as d:
        empty = dict(stamp="none", stages=[])
        with open(os.path.join(d, "campaign.json"), "w") as fh:
            json.dump(empty, fh)
        CAMPAIGNS[:] = [d]
        by, _homes, _st = load_many([d])
        refused = 0
        for _n, fn in FIGURES:
            try:
                fn(d, by, "none")
            except Missing:
                refused += 1
            except Exception as exc:                         # noqa: BLE001
                print("     (%s raised %s instead of refusing)"
                      % (fn.__name__, type(exc).__name__))
        check("every figure refuses an empty campaign (%d/%d)"
              % (refused, len(FIGURES)), refused == len(FIGURES))

        # A stage that FAILED must also refuse, not be treated as absent-ok.
        with open(os.path.join(d, "campaign.json"), "w") as fh:
            json.dump(dict(stamp="x", stages=[
                dict(key="teleop_motion", status="failed")]), fh)
        by, _homes, _st = load_many([d])
        try:
            teleop_generators(d, by, "x")
            check("a FAILED stage is refused", False)
        except Missing:
            check("a FAILED stage is refused", True)
    print("\n%d checks, %d failed" % (ok + fail, fail))
    return 1 if fail else 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--campaign", default="", nargs="*",
                    help="one or more campaign directories, merged in order; "
                         "a later one wins on a key it shares")
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args(argv)
    if a.self_test:
        return self_test()

    camps = list(a.campaign) if a.campaign else [newest_campaign()]
    CAMPAIGNS[:] = camps
    by, camp, stamp = load_many(camps)
    os.makedirs(a.out, exist_ok=True)
    print("campaign %s" % stamp)
    made = refused = 0
    for name, fn in FIGURES:
        try:
            body = fn(camp, by, stamp)
        except Missing as exc:
            print("  REFUSED  %-34s %s" % (name, exc))
            refused += 1
            continue
        with open(os.path.join(a.out, name), "w") as fh:
            fh.write(body)
        print("  wrote    %-34s %d bytes" % (name, len(body)))
        made += 1
    with open(os.path.join(a.out, "PROVENANCE.md"), "w") as fh:
        fh.write("Generated by `scripts/make_sim_figures.py` from:\n\n"
                 + "".join("* `%s`\n" % os.path.relpath(c, WS) for c in camps)
                 + "\n%d written, %d refused.\n" % (made, refused))
    print("\n%d written, %d refused -> %s"
          % (made, refused, os.path.relpath(a.out, WS)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
