_IK_RE = re.compile(r"(\d[\d\s]*)\s*IK calls[^\n]*?(?:TOTAL FAILURES:\s*(\d+)|,\s*(\d+) failures)")
_T1_WP = re.compile(r"waypoints\s+left (\d+), right (\d+), N=(\d+), floor ([\d.]+)")
_T1_FAIL = re.compile(r"^\s+(left|right)\s+(\d+) waypoints: (\d+) IK failures, (\d+) inside", re.M)
_T1_CLEAR = re.compile(r"worst clearance ([\d.]+) m")
_DANCE_RE = re.compile(r"^\s+(d\d)\s+dance: (\w+)\s+(\d+) of\s+(\d+) waypoints FAIL", re.M)


def _ikcalls(txt):
    m = re.search(r"([\d\s]+)IK calls", txt)
    if not m:
        raise Missing("no IK call count in the log")
    return int(m.group(1).replace(" ", ""))


def task_set(camp, by, stamp):
    """T1, the MSc set and the demonstration routines, in one table.

    Every row is IK success over a DENSIFIED path at N repeats, not a single
    call: TRAC-IK restarts randomly, so one call is one coin flip and a pose
    that passes once is not reachable.
    """
    for k in ("tasks_t1", "tasks_msc", "tasks_dance"):
        need(by, k)
    t1 = log_of(camp, "tasks_t1")
    msc = log_of(camp, "tasks_msc")
    dan = log_of(camp, "tasks_dance")

    wp = _T1_WP.search(t1)
    if not wp:
        raise Missing("T1's waypoint header did not parse")
    per = _T1_FAIL.findall(t1)
    if len(per) != 2:
        raise Missing("T1 did not report both arms")
    clear = min(float(c) for c in _T1_CLEAR.findall(t1)) if \
        _T1_CLEAR.findall(t1) else None
    dance = _DANCE_RE.findall(dan)
    if len(dance) != 3:
        raise Missing("the routines did not parse (%d rows)" % len(dance))

    n_t1, n_msc, n_dan = _ikcalls(t1), _ikcalls(msc), _ikcalls(dan)
    fails = (sum(int(p[2]) + int(p[3]) for p in per)
             + int(re.search(r"TOTAL FAILURES:\s*(\d+)", msc).group(1))
             + sum(int(d[2]) for d in dance))

    rows = []
    rows.append("    \\multicolumn{5}{@{}l}{\\itshape "
                "T1, both arms, pick and place by colour} \\\\")
    for arm, n, f, breach in per:
        rows.append("    \\quad %s arm & %s & %s & %s & %s \\\\"
                    % (arm, n, wp.group(3), f, breach))
    rows.append("    \\addlinespace[2pt]")
    rows.append("    \\multicolumn{5}{@{}l}{\\itshape "
                "the MSc task set} \\\\")
    for name, pat in (("T0 target reaching",
                       r"sampled: (\d+) poses, (\d+) unreachable"),):
        m = re.search(pat, msc)
        if m:
            rows.append("    \\quad %s & %s & 10 & %s & --- \\\\"
                        % (name, m.group(1), m.group(2)))
    for label, pat in (("T2 coordinated carry",
                        r"S1_short_lift\s+(\d+) waypoints, (\d+) failures"),
                       ("T3 circuit box",
                        r"circuit_box\s+right arm, (\d+) waypoints, (\d+) fail")):
        m = re.search(pat, msc)
        if m:
            rows.append("    \\quad %s & %s & 10 & %s & --- \\\\"
                        % (label, m.group(1), m.group(2)))
    m = re.search(r"(\d+) distinct clip waypoints tested at N=(\d+)", msc)
    if m:
        rows.append("    \\quad every recorded clip path & %s & %s & 0 & --- \\\\"
                    % (m.group(1), m.group(2)))
    rows.append("    \\addlinespace[2pt]")
    rows.append("    \\multicolumn{5}{@{}l}{\\itshape "
                "the demonstration routines} \\\\")
    for key, name, f, n in dance:
        rows.append("    \\quad %s (%s) & %s & 3 & %s & --- \\\\"
                    % (key, name, n, f))
    rows.append("    \\midrule")
    rows.append("    \\textbf{total} & \\multicolumn{2}{c}{\\textbf{%s IK calls}}"
                " & \\textbf{%d} & \\textbf{0} \\\\"
                % ("{:,}".format(n_t1 + n_msc + n_dan).replace(",", "\\,"),
                   fails))
    return (head(stamp, "the task set, inside the simulated platform")
            + "\\begin{tabular}{@{}lcccc@{}}\n"
              "  \\toprule\n"
              "  & waypoints & repeats & IK & floor \\\\\n"
              "  Path & densified & $N$ & failures & breaches \\\\\n"
              "  \\midrule\n"
            + "\n".join(rows)
            + "\n  \\bottomrule\n\\end{tabular}\n")


