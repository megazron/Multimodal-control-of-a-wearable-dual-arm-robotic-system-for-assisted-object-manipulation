class TrialLogger:
    """One instance per trial. Opens on start(), closes on finish()."""

    def __init__(self, root, participant, experiment, session=None):
        self.root = Path(root)
        self.participant = participant
        self.experiment = experiment
        self.session = session or time.strftime("%Y%m%d_%H%M%S")
        self.dir = self.root / participant
        self.dir.mkdir(parents=True, exist_ok=True)
        self.manifest_path = self.dir / f"manifest_{self.session}.json"
        self.summary_path = self.dir / f"summary_{self.session}.csv"
        self._f = None
        self._w = None
        self._t0 = None
        self.trial = None
        self._rows = 0
        if not self.summary_path.exists():
            with open(self.summary_path, "w", newline="") as f:
                csv.writer(f).writerow(TRIAL_COLUMNS)

    # ---------------------------------------------------------- manifest
    def write_manifest(self, **facts):
        """Facts about the RIG and the SESSION, not about a trial.

        Anything that could make an odd result interpretable belongs here:
        mounting, thresholds, which channels were alive, software version.
        """
        facts.setdefault("participant", self.participant)
        facts.setdefault("session", self.session)
        facts.setdefault("experiment", self.experiment)
        facts.setdefault("created", time.strftime("%Y-%m-%dT%H:%M:%S"))
        # Guard the anonymity rule in code, not in a README.
        banned = {"name", "email", "dob", "date_of_birth", "address", "phone"}
        bad = banned & {k.lower() for k in facts}
        if bad:
            raise ValueError(
                "manifest must not carry identifying fields: %s. Participant "
                "codes only - see docs/research/03_ethics_and_safety.md" % sorted(bad))
        with open(self.manifest_path, "w") as f:
            json.dump(facts, f, indent=2, sort_keys=True)
        return self.manifest_path

    # ------------------------------------------------------------- trial
    def start(self, trial_index, condition, scenario="", target_id="", arm="left",
              block=0):
        self.finish_open()
        self.trial = dict.fromkeys(TRIAL_COLUMNS, "")
        self.trial.update(participant=self.participant, session=self.session,
                          experiment=self.experiment, block=block,
                          trial_index=trial_index, condition=condition,
                          scenario=scenario, target_id=target_id, arm=arm,
                          valid=1, wall_clock=time.strftime("%Y-%m-%dT%H:%M:%S"))
        name = "%s_b%02d_t%03d_%s.csv" % (self.experiment, block, trial_index,
                                          str(condition).replace(" ", "_"))
        path = self.dir / name
        self._f = open(path, "w", newline="")
        self._w = csv.DictWriter(self._f, fieldnames=SAMPLE_COLUMNS,
                                 extrasaction="ignore")
        self._w.writeheader()
        self._t0 = time.monotonic()
        self._rows = 0
        return path

    def sample(self, **kw):
        if self._w is None:
            return
        kw.setdefault("t", round(time.monotonic() - self._t0, 4))
        row = {c: kw.get(c, "") for c in SAMPLE_COLUMNS}
        self._w.writerow(row)
        self._rows += 1
        # Flush every sample. At 50 Hz this is trivial, and it means a crash
        # costs at most one row instead of the trial.
        self._f.flush()

    def invalidate(self, reason):
        """Mark the trial INVALID rather than silently continuing.

        Used when a channel the current mode depends on drops out mid-trial.
        The trial is still written out - an invalid trial is data about the
        rig even when it is not data about the participant.
        """
        if self.trial is not None:
            self.trial["valid"] = 0
            self.trial["invalid_reason"] = reason

    def finish(self, **summary):
        if self.trial is None:
            return None
        self.trial.update({k: v for k, v in summary.items() if k in TRIAL_COLUMNS})
        unknown = set(summary) - set(TRIAL_COLUMNS)
        if unknown:
            raise KeyError("no column for %s - add it to TRIAL_COLUMNS rather "
                           "than dropping the metric" % sorted(unknown))
        with open(self.summary_path, "a", newline="") as f:
            csv.DictWriter(f, fieldnames=TRIAL_COLUMNS).writerow(self.trial)
        self.finish_open()
        t = self.trial
        self.trial = None
        return t

    def finish_open(self):
        if self._f is not None:
            self._f.close()
            self._f = None
            self._w = None

    @property
    def n_samples(self):
        return self._rows


def elapsed_columns_present(path):
    """Post-hoc check: does this CSV have every column the analysis needs?"""
    with open(path) as f:
        head = next(csv.reader(f))
    missing = [c for c in SAMPLE_COLUMNS if c not in head]
    return missing
