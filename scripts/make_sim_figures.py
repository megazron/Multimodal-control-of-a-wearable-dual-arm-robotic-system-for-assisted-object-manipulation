def cv_selftest(camp, by, stamp):
    need(by, "cv_arithmetic")
    root = camp.get("cv_arithmetic", "") if isinstance(camp, dict) else camp
    p = glob.glob(os.path.join(root, "cv_selftest", "**", "self_test.json"),
                  recursive=True)
    if not p:
        raise Missing("cv_arithmetic produced no self_test.json")
    checks = json.load(open(p[0]))["checks"]
    rows = []
    for c in checks:
        name = c["check"]
        det = c["detail"]
        control = name.startswith("THE CONTROL") or name.startswith("PLUMBING")
        name = re.sub(r"^THE CONTROL: ", "", name)
        name = re.sub(r"^PLUMBING: ", "", name)
        rows.append((name, det, control, c["passed"]))
    body = []
    for name, det, control, ok in rows:
        if det in ("", "None"):
            det = "---"
        else:
            try:                       # a bare number: give it a sane width
                det = "%.3g" % float(det)
            except ValueError:
                pass                   # it already carries its unit
        body.append("    %s%s & %s & %s \\\\"
                    % ("\\textit{control:} " if control else "",
                       _tex(name), _tex(det), "\\checkmark" if ok else "FAIL"))
    return (head(stamp, "the vision pipeline against a constructed scene")
            + "\\begin{tabular}{@{}p{0.60\\linewidth}rc@{}}\n"
              "  \\toprule\n"
              "  What was checked & Measured & \\\\\n"
              "  \\midrule\n"
            + "\n".join(body)
            + "\n  \\bottomrule\n\\end{tabular}\n")


