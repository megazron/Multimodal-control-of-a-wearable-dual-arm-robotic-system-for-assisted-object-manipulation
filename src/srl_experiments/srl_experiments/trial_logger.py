#!/usr/bin/env python3
"""
trial_logger.py — the shared logging library. Every experiment uses this one.

DESIGN RULES, each of which exists because the alternative loses data:

  * ONE CSV PER TRIAL plus a session manifest. A single giant file means one
    crash loses the session; per-trial files mean it loses one trial.
  * ROWS ARE APPENDED AND FLUSHED as they are produced. Buffering until the
    end of a trial is how a crash costs you the trial you most want.
  * ANONYMISED IDS ONLY. No name, email, date of birth or free text that could
    carry one reaches any file. The participant code is generated by the
    runner and the mapping, if one is kept at all, lives outside the repo.
  * EVERY METRIC HAS A COLUMN EVEN WHEN IT IS EMPTY. A missing column and a
    missing measurement look identical afterwards; an empty column does not.
  * The manifest records what was TRUE OF THE RIG, not just of the trial:
    which channels were live, which mounting, what payload, what thresholds.
    Those are the covariates that make an odd result interpretable.
"""
